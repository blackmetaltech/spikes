#!/usr/bin/env python3
"""Generates the diagnosis circuits circuits/dx_*.json: the reference circuit of the underlying task with the hidden lesion applied
(the answer's projections are kept in the file with their weight set to 0, so every candidate is drawn and can be cut or probed;
the missing connection is the one whose cell is silent although its source fires). The boss circuits are generated by circuits/tools/gen_bosses.py.
Run from anywhere:  python3 circuits/tools/gen_boss_dx.py [dx_clonus ...]
Lesion ids are the lesion lab's: 'pre>post' (all projections pre -> post), several joined with '+'. Cases: docs/circuits/dx_*.md."""
import json, os, sys
import dx_types

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, ".."))

CASES = {
    "dx_clonus": ("renshaw.json", "MN_F>RC_F+MN_E>RC_E"),
    "dx_vagal": ("heart_autonomic.json", "NA>VG"),
    "dx_orthostatic": ("baroreflex.json", "RVLM>IML"),
    "dx_apnoea": ("breathing.json", "RTN>PBC+RTN>PHR"),
    "dx_horner": ("pupil.json", "IML>SCG"),
    "dx_achalasia": ("peristalsis.json", "DIN>IMN"),
}


def lesion(c, lid):
    """Silence every projection pre -> post named by `lid`: weight 0 (rule projections: synapse.weight, edge lists: each edge weight).
    The projection stays in the file, so the lesion lab can select it and the circuit view draws it like any other axon."""
    hit = [tuple(x.split(">")) for x in lid.split("+")]
    n = 0
    for p in c["projections"]:
        if (p["pre"], p["post"]) not in hit:
            continue
        n += 1
        if "edges" in p:
            for e in p["edges"]:
                e[2] = 0.0
        else:
            assert isinstance(p["synapse"]["weight"], (int, float)), "weight distributions are not supported here"
            p["synapse"]["weight"] = 0.0
    assert n >= len(hit), f"lesion {lid} matched too few projections"
    return c


def main():
    which = sys.argv[1:] or list(CASES)
    for cid in which:
        ref, lid = CASES[cid]
        c = json.load(open(os.path.join(OUT, ref)))
        c = lesion(c, lid)
        c["name"] = "Patient circuit: " + cid[3:]
        c["meta"] = {"author": "spike", "task": cid, "notes": f"docs/circuits/{cid}.md"}
        dx_types.annotate(c, json.load(open(os.path.join(OUT, ref))))
        with open(os.path.join(OUT, cid + ".json"), "w") as f:
            json.dump(c, f, indent=1)
            f.write("\n")
        print(f"wrote circuits/{cid}.json from {ref} ({len(c['projections'])} projections)")


if __name__ == "__main__":
    main()
