#!/usr/bin/env python3
"""The circuits of the worm chapter of the Atlas wing (chapter a_worm; research/atlas-a.md 4b; engine/src/tasks/atlas_worm.h). Run from anywhere: python3 godot/circuits/tools/gen_atlas_worm.py

Writes, next to this script's circuits/ directory:
  a_path_given.json    the given touch circuit (every population and projection locked; five cell-type groups AVA, AVB, AVD, AVE, PVC, sign fixed (+1), scale free from 0 to 1, given at 1)
  a_path.json          its reference for a_path: the classes of one shortest route kept (AVD), the others silenced (scale 0)
  a_predict_given.json = a_predict.json = a_path_given.json (a bet: the level silences the committed class itself)
  a_motif_given.json   the whole chemical wiring of the hermaphrodite (302 cells, classes as populations, locked, no stimulus; four category groups with nothing free) = a_motif.json
  dx_a_worm.json       the patient of the diagnosis case: the touch circuit, not locked, no groups, the outputs of one class (the answer) at weight 0

The touch circuit is tools/connectome/worm_circuit.build with the fixed model point POINT (every synapse excitatory, weight = synapse count x scale_chem, no electrical coupling,
synapse floor min_count, background current I_e, tau_syn_ex); the data are data/connectome/worm/touch.json and whole.json (Cook et al. 2019, via OpenWorm cect; see PROVENANCE.md there).
The stored weight of a projection is a magnitude in pA; a group applies |w| x scale x sign at load. The touch is the level's own Poisson sensor "touch_head" (150 Hz per cell, weight 1000 pA)
on the head touch cells ALM and AVM; the motors are "reverse" (DA, VA) and "forward" (DB, VB). meta.cells lists the cell names in circuit neuron order.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..", "..", "tools", "connectome")))
import worm_circuit as wc

# the model point (research/atlas-a.md 4b, "The model point of the levels")
POINT = dict(scale_chem=15.5, I_e=170.0, min_count=3, tau_syn_ex=2.0)
SOURCE = ("C. elegans hermaphrodite connectome, Cook SJ et al. 2019, Nature 571:63-71, doi:10.1038/s41586-019-1352-7, read through OpenWorm cect 0.3.5; "
          "the data keep the terms of the original publication; extraction: tools/connectome/worm_table.py; data/connectome/worm/PROVENANCE.md")
ANSWER_A_PATH = ("AVD",)           # the route kept in the reference of a_path (shortest routes at class level: through AVB, AVD or AVE)
ANSWER_DX = "PVC"                   # the class silenced in the patient of dx_a_worm
LAYOUT = {"ALM": (90, 140), "AVM": (90, 260), "PLM": (90, 380), "AVA": (340, 80), "AVB": (340, 190), "AVD": (340, 300), "AVE": (340, 410), "PVC": (340, 520),
          "DA": (600, 100), "VA": (600, 240), "DB": (600, 380), "VB": (600, 520)}


def touch_circuit(scales, name, locked=True, groups=True, silent_outputs=()):
    c = wc.build(dict(scale_chem=POINT["scale_chem"], I_e=POINT["I_e"], min_count=POINT["min_count"], tau_syn_ex=POINT["tau_syn_ex"], tau_syn_in=POINT["tau_syn_ex"]))
    c["name"] = name
    c["seed"] = 7
    cells = c["meta"]["cells"]
    first = 0
    for p in c["populations"]:
        if locked:
            p["locked"] = True
        cx, cy = LAYOUT[p["id"]]
        p["pos"] = [[cx + 34 * (k % 2), cy + 22 * (k // 2)] for k in range(p["n"])]
        p["role"] = "neuron"
        first += p["n"]
    for pr in c["projections"]:
        for e in pr["edges"]:
            e[2] = abs(e[2])                          # stored weights are magnitudes
        if pr["pre"] in silent_outputs:
            for e in pr["edges"]:
                e[2] = 0.0
        if locked:
            pr["locked"] = True
    if groups:
        c["groups"] = [{"id": k, "label": "Interneuron class " + k, "pops": [k], "sign": 1, "scale": scales[k], "free": ["scale"], "ranges": {"scale": [0.0, 1.0]}, "off": True}
                       for k in wc.COMMAND]
    c["inputs"] = [{"name": "touch_head", "kind": "poisson", "targets": [{"pop": "ALM"}, {"pop": "AVM"}], "weight": 1000.0, "value": 0.0}]
    c["outputs"] = [{"name": "reverse", "kind": "rate", "neurons": [{"pop": "DA"}, {"pop": "VA"}]},
                    {"name": "forward", "kind": "rate", "neurons": [{"pop": "DB"}, {"pop": "VB"}]}]
    c["record"] = {"spikes": "all"}
    c["meta"] = {"author": "spike", "task": "a_worm", "source": SOURCE, "cells": cells,
                 "model_point": POINT, "notes": "touch circuit of the worm chapter: every synapse excitatory, weight = synapse count x scale_chem (a stored magnitude), no electrical coupling, "
                                                "synapses with fewer than min_count contacts left out; generated by circuits/tools/gen_atlas_worm.py"}
    return c


def whole_circuit():
    d = json.load(open(os.path.normpath(os.path.join(HERE, "..", "..", "..", "data", "connectome", "worm", "whole.json"))))
    ns = d["neurons"]
    cats = ["sensory", "interneuron", "motor", "other"]
    classes = {}
    for i, n in enumerate(ns):
        classes.setdefault(n["class"], []).append(i)
    order = sorted(classes, key=lambda k: (cats.index(ns[classes[k][0]]["category"]), k))
    local, cls = {}, {}
    for k in order:
        for j, i in enumerate(classes[k]):
            local[i] = j; cls[i] = k
    pops = [{"id": k, "model": "iaf_psc_alpha", "n": len(classes[k]), "params": {}, "role": "neuron", "locked": True} for k in order]
    edges = {}
    for a, b, n in d["chemical"]:
        edges.setdefault((cls[a], cls[b]), []).append([local[a], local[b], float(n), 2.0])
    idx = {k: i for i, k in enumerate(order)}
    proj = [{"pre": a, "post": b, "locked": True, "synapse": {"synapse_model": "static_synapse"}, "edges": e}
            for (a, b), e in sorted(edges.items(), key=lambda kv: (idx[kv[0][0]], idx[kv[0][1]]))]
    groups = [{"id": ct, "label": "Cell type: " + ct, "pops": [k for k in order if ns[classes[k][0]]["category"] == ct], "sign": 1, "scale": 1.0, "free": []} for ct in cats]
    cells = [ns[i]["name"] for k in order for i in classes[k]]
    return {"schema_version": 1, "name": "Atlas: the whole chemical wiring of the worm", "resolution_ms": 0.1, "seed": 7, "populations": pops, "groups": groups, "projections": proj,
            "inputs": [], "outputs": [], "record": {"spikes": "all"},
            "meta": {"author": "spike", "task": "a_motif", "source": SOURCE, "cells": cells,
                     "notes": "the chemical graph of whole.json (every directed pair with its synapse count, stored as the weight magnitude in pA; self-connections kept; electrical couplings not included); "
                              "the four groups are the cell-type blocks (category of the data set) and have nothing free; no stimulus: the level reads the wiring; generated by circuits/tools/gen_atlas_worm.py"}}


def put(name, c):
    with open(os.path.join(OUT, name), "w") as f:
        json.dump(c, f, indent=1)
        f.write("\n")


if __name__ == "__main__":
    ones = {k: 1.0 for k in wc.COMMAND}
    given = touch_circuit(ones, "Atlas: the given touch circuit of the worm")
    put("a_path_given.json", given)
    put("a_predict_given.json", given)
    put("a_path.json", touch_circuit({k: 1.0 if k in ANSWER_A_PATH else 0.0 for k in wc.COMMAND}, "Atlas: the route AVD kept alone (reference)"))
    put("a_predict.json", given)   # a bet: the level silences the committed class itself, so its circuit is the given one
    w = whole_circuit()
    put("a_motif_given.json", w)
    put("a_motif.json", w)
    put("dx_a_worm.json", touch_circuit(ones, "Diagnosis: the worm that does not back up", locked=False, groups=False, silent_outputs=(ANSWER_DX,)))
    print("wrote a_path(_given), a_predict(_given), a_motif(_given), dx_a_worm in", OUT)
